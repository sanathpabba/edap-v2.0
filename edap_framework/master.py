"""Master runner: trigger the per-pipeline Databricks jobs in the right order, with parameters, and report each result.

  Common (landing, bronze, silver, gold)  ->  then the asset classes IN PARALLEL (each: bronze, silver, gold, consumption)

Used by the master_runner notebook (deployment/notebooks/master_runner.py) and by the console command `edap-master`.
The jobs (generated by tools/generate_pipelines.py) are edap-common, edap-equities, edap-fixedincome, edap-fx, edap-commodities; every one takes the same job
parameters: mode (Routine|Adhoc), stages (comma list), date, expect_file, extra. If Common fails the asset classes are not started."""
import argparse
import sys
import time

from edap_framework.core import config

STAGES = ["landing", "bronze", "silver", "gold", "consumption"]
MODES = ["Routine", "Adhoc"]
TERMINAL = {"TERMINATED", "SKIPPED", "INTERNAL_ERROR"}


class MasterFailed(Exception):
    """A job could not be found/started, or one of the triggered runs did not succeed."""


def job_name(asset_class):
    return "edap-" + asset_class.folder.lower()


def split_list(text):
    return [x.strip() for x in str(text or "").replace(";", ",").split(",") if x.strip()]


def select_pipelines(asset_classes="ALL"):
    """ALL, or a comma list of folder / prefix / name (Equities, fixed_income, 'Foreign Exchange', Common ...)."""
    everything = config.list_asset_classes()
    names = split_list(asset_classes)
    if not names or any(n.upper() == "ALL" for n in names):
        return everything
    out = []
    for n in names:
        match = [a for a in everything if n.lower() in (a.folder.lower(), a.prefix.lower(), a.name.lower())]
        if not match:
            raise MasterFailed("unknown asset class %r (choose from: ALL, %s)" % (n, ", ".join(a.folder for a in everything)))
        out.append(match[0])
    return out


def build_plan(asset_classes="ALL", stages=None):
    """Waves of pipelines: wave 1 = Common (if selected and it has a selected stage), wave 2 = the asset classes (run in parallel).
    A pipeline is included only if at least one selected stage is one of its layers."""
    chosen_stages = split_list(stages) or list(STAGES)
    bad = [s for s in chosen_stages if s not in STAGES]
    if bad:
        raise MasterFailed("unknown stage(s) %s (choose from: %s)" % (bad, ", ".join(STAGES)))
    chosen = select_pipelines(asset_classes)
    relevant = [a for a in chosen if set(chosen_stages) & set(a.items)]
    waves = [[a for a in relevant if a.prefix == "common"], sorted([a for a in relevant if a.prefix != "common"], key=lambda a: a.folder)]
    return {"stages": [s for s in STAGES if s in chosen_stages], "waves": [w for w in waves if w]}


def extra_tokens(from_ts="", to_ts="", fx_mode="", rescan=False, rebuild=False, notify=False, extra=""):
    """The `extra` job parameter: space-separated key=value pairs the pipeline reads (no spaces inside values: use 2026-11-17T00:00:00)."""
    tokens = ["%s=%s" % (k, v) for k, v in (("from_ts", from_ts), ("to_ts", to_ts), ("fx_mode", fx_mode)) if v]
    tokens += [k + "=true" for k, on in (("rescan", rescan), ("rebuild", rebuild), ("notify", notify)) if on]
    return " ".join(tokens + ([extra.strip()] if extra and extra.strip() else []))


def job_parameters(stages, mode="Routine", date="", expect_file="auto", extra=""):
    if mode not in MODES:
        raise MasterFailed("mode must be one of %s" % MODES)
    exp = expect_file if expect_file in ("true", "false") else ("true" if mode == "Routine" else "false")      # an Adhoc backfill must not expect yesterday's file
    return {"mode": mode, "stages": ",".join(stages), "date": date or "", "expect_file": exp, "extra": extra or ""}


def find_job_id(w, name):
    """Job id by name. Bundles deployed in development mode prefix the name ('[dev user] edap-equities'), so match on the end of the name."""
    matches = [j for j in w.jobs.list() if ((j.settings.name if j.settings else "") or "").endswith(name)]
    exact = [j for j in matches if j.settings.name == name]
    pool = exact or matches
    if not pool:
        raise MasterFailed("job '%s' not found: deploy the jobs first (release workflow with deploy_jobs ticked)" % name)
    return sorted(pool, key=lambda j: getattr(j, "created_time", 0) or 0)[-1].job_id


def _val(x):
    return getattr(x, "value", x) if x is not None else None


def _state(run):
    s = run.state
    return _val(s.life_cycle_state), _val(s.result_state)


def _failed_tasks(run):
    return [t.task_key for t in (run.tasks or []) if _val(getattr(t.state, "result_state", None)) not in (None, "SUCCESS")]


def run_wave(w, items, params, wait=True, poll_seconds=15, sleep=time.sleep, log=print, timeout_seconds=6 * 3600):
    """Trigger every (label, job_id) of the wave at once, then poll until all are finished. Returns one result dict per job."""
    runs = {}
    for label, job_id in items:
        waiter = w.jobs.run_now(job_id=job_id, job_parameters=params)
        runs[label] = {"label": label, "job_id": job_id, "run_id": waiter.run_id, "life": "PENDING", "result": None, "started": time.time()}
        log("  started %-14s job %s run %s" % (label, job_id, waiter.run_id))
    if not wait:
        return list(runs.values())
    deadline = time.time() + timeout_seconds
    while True:
        pending = [r for r in runs.values() if r["life"] not in TERMINAL]
        if not pending:
            break
        if time.time() > deadline:
            raise MasterFailed("timed out waiting for %s" % [r["label"] for r in pending])
        sleep(poll_seconds)
        for r in pending:
            run = w.jobs.get_run(r["run_id"])
            r["life"], r["result"] = _state(run)
            r["url"] = getattr(run, "run_page_url", "")
            if r["life"] in TERMINAL:
                r["seconds"] = int(time.time() - r["started"])
                r["failed_tasks"] = _failed_tasks(run) if r["result"] != "SUCCESS" else []
                log("  finished %-14s %s %s%s" % (r["label"], r["life"], r["result"] or "", ("  failed tasks: " + ", ".join(r["failed_tasks"])) if r["failed_tasks"] else ""))
    return list(runs.values())


def run_master(w, asset_classes="ALL", stages="", mode="Routine", date="", expect_file="auto", extra="", dry_run=False, wait=True,
               poll_seconds=15, sleep=time.sleep, log=print):
    """Plan, trigger and wait. Raises MasterFailed after reporting if anything failed (so the notebook / command fails)."""
    plan = build_plan(asset_classes, stages)
    params = job_parameters(plan["stages"], mode, date, expect_file, extra)
    log("stages: %s | mode: %s | date: %s | expect_file: %s | extra: %s" % (",".join(plan["stages"]), mode, date or "(today)", params["expect_file"], extra or "-"))
    for i, wave in enumerate(plan["waves"], 1):
        log("wave %d (%s): %s" % (i, "in parallel" if len(wave) > 1 else "single", ", ".join(job_name(a) for a in wave)))
    if not plan["waves"]:
        raise MasterFailed("nothing to run: none of the selected pipelines has any of the selected stages")
    ids = {a.folder: find_job_id(w, job_name(a)) for wave in plan["waves"] for a in wave}          # all jobs must exist before anything starts
    if dry_run:
        log("dry run: nothing triggered. Job ids: %s" % ids)
        return {"dry_run": True, "params": params, "waves": [[a.folder for a in wv] for wv in plan["waves"]], "job_ids": ids}
    results, failed = [], []
    for i, wave in enumerate(plan["waves"], 1):
        if failed:
            log("wave %d skipped: an earlier wave failed (%s)" % (i, ", ".join(failed)))
            results += [{"label": a.folder, "life": "NOT_STARTED", "result": "SKIPPED_UPSTREAM_FAILED"} for a in wave]
            continue
        done = run_wave(w, [(a.folder, ids[a.folder]) for a in wave], params, wait, poll_seconds, sleep, log)
        results += done
        failed = [r["label"] for r in done if wait and (r["result"] != "SUCCESS")]
    summary = {"params": params, "results": results}
    log("\nSUMMARY")
    for r in results:
        log("  %-14s %-12s %-24s %s" % (r["label"], r.get("life"), r.get("result") or "-", r.get("url", "")))
    if failed:
        raise MasterFailed("failed: %s" % ", ".join(failed))
    return summary


def main(argv=None):
    ap = argparse.ArgumentParser(description="Trigger the EDAP pipeline jobs in order: Common first, then the asset classes in parallel.")
    ap.add_argument("--asset-classes", default="ALL", help="ALL or a comma list: Common,Equities,FixedIncome,FX,Commodities")
    ap.add_argument("--stages", default="", help="comma list of %s (empty = all)" % ",".join(STAGES))
    ap.add_argument("--mode", default="Routine", choices=MODES)
    ap.add_argument("--date", default="", help="run date YYYY-MM-DD (empty = today); the positions file expected and the FX day follow it")
    ap.add_argument("--expect-file", default="auto", choices=["auto", "true", "false"])
    ap.add_argument("--from-ts", default=""); ap.add_argument("--to-ts", default=""); ap.add_argument("--fx-mode", default="", choices=["", "daily", "history"])
    ap.add_argument("--rescan", action="store_true"); ap.add_argument("--rebuild", action="store_true"); ap.add_argument("--notify", action="store_true")
    ap.add_argument("--extra", default="", help="more key=value pairs, space separated")
    ap.add_argument("--dry-run", action="store_true"); ap.add_argument("--no-wait", action="store_true")
    a = ap.parse_args(argv)
    from databricks.sdk import WorkspaceClient
    try:
        run_master(WorkspaceClient(), a.asset_classes, a.stages, a.mode, a.date, a.expect_file,
                   extra_tokens(a.from_ts, a.to_ts, a.fx_mode, a.rescan, a.rebuild, a.notify, a.extra), a.dry_run, not a.no_wait)
    except MasterFailed as exc:
        print("MASTER FAILED: %s" % exc, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
