"""Onboard a SQL table by YAML only: generate landing + bronze + minimal DQ specs from the source contract entry.
Add the table to definitions/sources/<source>.yml, run runners/scaffold_sql_table.py, review the files, done (no code change)."""
import os

import yaml

from edap_framework.core import config


def _q(t):
    return '"%s"' % t if "(" in t else t


def scaffold(object_name, source_file="definitions/sources/azure_sql_trading.yml", root=None, overwrite=False):
    root = root or config.project_root()
    src = config.load_yaml(source_file)
    o = next(x for x in src["objects"] if x["name"] == object_name)
    tbl, cols = object_name.split(".")[1], o["columns"]
    big = tbl == "trades"
    collist = "\n".join("    - %s" % c for c in cols)
    coldef = "\n".join("  %s: %s" % (c, _q(t)) for c, t in cols.items())
    part = ("\n  partition_column: trade_dt" if big else "")
    landing = f"""# Landing spec: extract {object_name} from Azure SQL and write Parquet files into ADLS landing.
# Processed on its own (runners/landing_sql.py --table {tbl}); no other source or table is touched.
version: 1
layer: landing
source_system: {src['source_system']}
source_definition: {source_file}
table: {tbl}
source_object: {object_name}
extract:
  method: jdbc
  load_type: incremental            # first run (no stored watermark) = full initial load; later runs = delta
  watermark_column: {o['watermark_column']}
  initial_load: full
  fetch_size: {20000 if big else 5000}
  num_partitions: {4 if big else 1}{part}
  columns:
{collist}
target:
  container: landing
  path: sql/{tbl}                    # files land under sql/{tbl}/ingest_date=YYYY-MM-DD/batch_id=<id>/
  format: parquet
  mode: append
watermark:
  store: edap.metadata.watermarks    # key = {src['source_system']}.{object_name}
  advance_after_success: true        # watermark moves only after the landing write succeeded
audit:
  run_log: edap.audit.ingestion_runs
"""
    bk = "[" + ", ".join(o["business_key"]) + "]"
    bronze = f"""# Bronze spec: raw, append-only copy of {object_name} (no cleansing, no dedup - that is Silver's job).
# Processed on its own (runners/bronze_load.py --source sql-loads --table {tbl}).
version: 1
layer: bronze
source_system: {src['source_system']}
source_object: {object_name}
table: {tbl}
input:
  landing_spec: definitions/landing/sql-loads/{tbl}.yml
  container: landing
  path: sql/{tbl}
  format: parquet
  reader: autoloader                 # cloudFiles, availableNow trigger => incremental by file
target:
  catalog: edap
  schema: bronze
  table: sql_{tbl}
  mode: append
  partition_by: [_ingest_date]
  properties:
    delta.enableChangeDataFeed: "true"
business_key: {bk}
columns:
{coldef}
audit_columns:                       # added by the framework, identical for every Bronze table
  _source_system: {src['source_system']}
  _source_object: {object_name}
  _batch_id: bronze_run_batch
  _ingest_ts: current_timestamp
  _ingest_date: current_date
  _source_file: file_path
lineage:
  landing_batch: path            # landing batch_id read from the landing folder name (batch_id=...)
  row_hash: sha256                  # _row_hash over the source columns; detects changed/replayed rows without comparing every column
  stamp: [_run_id, _spec_path, _spec_version, _landing_batch_id]
governance:                         # applied as Unity Catalog comment and tags on the Bronze table
  description: "Raw Azure SQL {tbl}, append-only, as extracted"
  owner: {src['owner']}
  sensitivity: {src['sensitivity']}
checkpoint:
  container: bronze
  path: _checkpoints/sql_{tbl}
dq:
  rules_file: definitions/dq_rules/bronze/sql_{tbl}.yml   # authored in the DQ phase
  mode: later
"""
    rules = {"version": 1, "rule_set": "bronze.sql_%s" % tbl, "layer": "bronze", "target_table": "edap.bronze.sql_%s" % tbl, "mode": "quarantine",
             "description": "Starter checks generated by the scaffold: business key present and unique; extend as needed",
             "checks": [{"name": "%s_not_null" % k, "criticality": "error", "check": {"function": "is_not_null", "arguments": {"column": k}}} for k in o["business_key"]]
                       + [{"name": "%s_unique" % "_".join(o["business_key"]), "criticality": "error", "check": {"function": "is_unique", "arguments": {"columns": o["business_key"]}}}]}
    out = {"definitions/landing/sql-loads/%s.yml" % tbl: landing, "definitions/bronze/sql-loads/%s.yml" % tbl: bronze,
           "definitions/dq_rules/bronze/sql_%s.yml" % tbl: "# Starter DQX rule set (edit freely).\n" + yaml.dump(rules, sort_keys=False, width=200)}
    written = []
    for rel, text in out.items():
        path = os.path.join(root, rel)
        if os.path.exists(path) and not overwrite:
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write(text)
        written.append(rel)
    return written
